export type LocaleCode = keyof typeof messages;
export type MessageKey = keyof (typeof messages)['it'];
export type Messages = Record<MessageKey, string>;
const completeCatalogs: Record<LocaleCode, Messages> = messages;

export function useLocale(): {
  locale: LocaleCode;
  isRTL: boolean;
  t: Messages;
} {
  const locale = useMemo<LocaleCode>(() => {
    const deviceLanguage = getLocales()[0]?.languageCode?.toLowerCase();
    return deviceLanguage && deviceLanguage in messages
      ? (deviceLanguage as LocaleCode)
      : 'it';
  }, []);

  return {
    locale,
    isRTL: locale === 'ar',
    t: completeCatalogs[locale],
  };
}
